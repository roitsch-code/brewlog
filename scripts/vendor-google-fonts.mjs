// Vendor the app's Google Fonts into the repo, so `next build` never touches
// the network for fonts.
//
//   node scripts/vendor-google-fonts.mjs
//
// Why: `next/font/google` fetches CSS + font files from Google on EVERY build.
// When Google answers oddly the build dies (2026-10-07/08/10: four failed
// deploys, "Cannot read properties of null (reading '1')" in
// next/font/google/loader.js — a font URL without a file extension). The VPS
// build has no fallback, so a Google hiccup = no deploy.
//
// This script produces exactly what next/font/google produced at build time,
// using Next's OWN helpers (same Google URL, same user agent, same fallback
// metrics), and writes it to src/app/fonts/ + src/app/fonts.css. Run it again
// only when a font, weight or style changes. Output is committed.

import { createRequire } from "node:module";
import { mkdir, writeFile, readdir, unlink } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

const require = createRequire(import.meta.url);
const G = "next/dist/compiled/@next/font/dist/google";
const { getFontAxes } = require(`${G}/get-font-axes`);
const { getGoogleFontsUrl } = require(`${G}/get-google-fonts-url`);
const { fetchCSSFromGoogleFonts } = require(`${G}/fetch-css-from-google-fonts`);
const { findFontFilesInCss } = require(`${G}/find-font-files-in-css`);
const { getFallbackFontOverrideMetrics } = require(`${G}/get-fallback-font-override-metrics`);
const { fetchFontFile } = require(`${G}/fetch-font-file`);

// Mirrors the next/font/google calls that lived in src/app/layout.tsx.
const FONTS = [
  { family: "JetBrains Mono", weights: ["400", "500"], styles: ["normal"], display: "swap", variable: "--font-jetbrains-mono" },
  { family: "Instrument Serif", weights: ["400"], styles: ["normal", "italic"], display: "swap", variable: "--font-instrument-serif" },
  { family: "Fraunces", weights: ["400", "500", "600"], styles: ["normal"], display: "swap", variable: "--font-fraunces" },
  { family: "Chivo", weights: ["200", "400", "500", "600"], styles: ["normal"], display: "swap", variable: "--font-chivo" },
];

const ROOT = process.cwd();
const FONT_DIR = path.join(ROOT, "src/app/fonts");
const CSS_OUT = path.join(ROOT, "src/app/fonts.css");

const scoped = (name) => `'__btts_${name.replace(/ /g, "_")}'`;

await mkdir(FONT_DIR, { recursive: true });
for (const f of await readdir(FONT_DIR)) if (f.endsWith(".woff2")) await unlink(path.join(FONT_DIR, f));

const blocks = [];
const vars = [];
let fileCount = 0;

for (const font of FONTS) {
  const axes = getFontAxes(font.family, font.weights, font.styles, undefined);
  const url = getGoogleFontsUrl(font.family, axes, font.display);
  let css = await fetchCSSFromGoogleFonts(url, font.family, false);
  css = css.split("body {", 1)[0];

  const files = findFontFilesInCss(css);
  if (!files.length) throw new Error(`No font files in Google CSS for ${font.family}`);
  for (const { googleFontFileUrl } of files) {
    if (!/\.woff2$/.test(googleFontFileUrl)) {
      throw new Error(`Unexpected font URL for ${font.family}: ${googleFontFileUrl}`);
    }
    const buf = await fetchFontFile(googleFontFileUrl, false);
    if (!buf || buf.length < 1000) throw new Error(`Font file too small: ${googleFontFileUrl}`);
    const name = `${font.family.toLowerCase().replace(/ /g, "-")}-${createHash("sha1").update(buf).digest("hex").slice(0, 10)}.woff2`;
    await writeFile(path.join(FONT_DIR, name), buf);
    css = css.split(googleFontFileUrl).join(`./fonts/${name}`);
    fileCount++;
  }
  css = css.replace(new RegExp(`font-family: '${font.family}';`, "g"), `font-family: ${scoped(font.family)};`);

  const m = getFallbackFontOverrideMetrics(font.family);
  const families = [scoped(font.family)];
  if (m) {
    const fb = scoped(`${font.family} Fallback`);
    families.push(fb);
    css += `@font-face {\n  font-family: ${fb};\n  src: local("${m.fallbackFont}");\n` +
      (m.ascentOverride ? `  ascent-override: ${m.ascentOverride};\n` : "") +
      (m.descentOverride ? `  descent-override: ${m.descentOverride};\n` : "") +
      (m.lineGapOverride ? `  line-gap-override: ${m.lineGapOverride};\n` : "") +
      (m.sizeAdjust ? `  size-adjust: ${m.sizeAdjust};\n` : "") +
      `}\n`;
  }
  blocks.push(`/* ── ${font.family} — ${font.weights.join("/")} ${font.styles.join("/")} */\n${css.trim()}`);
  vars.push(`  ${font.variable}: ${families.join(", ")};`);
}

const header = `/* GENERATED by scripts/vendor-google-fonts.mjs — do not edit by hand.
 * Self-hosted copies of the Google Fonts the app uses, so \`next build\` needs
 * no network for fonts (four deploys failed on a Google fetch, Oct 2026).
 * Files live in src/app/fonts/ and are bundled by Next into
 * /_next/static/media (exempt from the auth middleware, unlike /public). */\n\n`;

await writeFile(CSS_OUT, `${header}${blocks.join("\n\n")}\n\n:root {\n${vars.join("\n")}\n}\n`);
console.log(`wrote ${fileCount} font files + src/app/fonts.css`);
